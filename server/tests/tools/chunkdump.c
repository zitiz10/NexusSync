/*
 * chunkdump — writes tests/fixtures/chunks_expected.txt from the C
 * chunkers. Run via `make fixtures-expected` after an intentional chunker
 * change (which is a format version bump, SPEC §6.2). The TS parity test
 * and test_chunk compare against this file.
 */
#include "chunk_fixtures.h"
#include "nx_test_util.h"

#include <inttypes.h>
#include <stdio.h>

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: chunkdump <fixture-data-dir> <out-file>\n");
        return 2;
    }
    FILE *out = fopen(argv[2], "wb");
    if (!out) {
        perror(argv[2]);
        return 1;
    }
    fprintf(out, "# GENERATED by server/tests/tools/chunkdump.c from the C chunkers.\n"
                 "# Format: see server/tests/chunk_fixtures.h. Regenerate: make fixtures-expected\n");
    for (size_t i = 0; i < NX_CHUNK_FIXTURE_COUNT; i++) {
        const char *name = NX_CHUNK_FIXTURES[i];
        char path[1024];
        snprintf(path, sizeof path, "%s/%s", argv[1], name);
        size_t n = 0;
        uint8_t *buf = nx_read_file(path, &n);
        if (!buf) {
            fprintf(stderr, "cannot read %s: %s\n", path, plat_last_error());
            return 1;
        }
        uint8_t fh[32], dg[32];
        char hex[65];
        nx_sha256(buf, n, fh);
        nx_hex(fh, 32, hex);
        fprintf(out, "file %s %zu %s\n", name, n, hex);

        nx_chunk_list l;
        if (nx_chunk_all(NX_CHUNKER_CDC, buf, n, 0, &l, dg) != 0)
            return 1;
        nx_hex(dg, 32, hex);
        fprintf(out, "cdc %s %zu %s ", name, l.count, hex);
        if (l.count == 0)
            fputc('-', out);
        for (size_t k = 0; k < l.count; k++)
            fprintf(out, k ? ",%" PRIu32 : "%" PRIu32, l.lens[k]);
        fputc('\n', out);
        nx_chunk_list_free(&l);

        if (nx_chunk_all(NX_CHUNKER_FIXED, buf, n, 0, &l, dg) != 0)
            return 1;
        nx_hex(dg, 32, hex);
        fprintf(out, "fixed %s %zu %s\n", name, l.count, hex);
        nx_chunk_list_free(&l);
        free(buf);
    }
    if (fclose(out) != 0) {
        perror("fclose");
        return 1;
    }
    return 0;
}
