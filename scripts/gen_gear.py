#!/usr/bin/env python3
"""Generate the 256-entry Gear table for the content-defined chunker
(SPEC §6.2) and write it for both C and TypeScript from one seed, so the
server and the browser always cut files at exactly the same places.

    python3 scripts/gen_gear.py          # (re)write both files
    python3 scripts/gen_gear.py --check  # exit 1 if either file is stale

Values: SplitMix64 seeded with 0x4E657875735379 ("NexusSy" in ASCII),
upper 32 bits of each of the first 256 outputs.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = 0x4E657875735379
MASK64 = (1 << 64) - 1
C_OUT = ROOT / "server/src/engine/gear_table.h"
TS_OUT = ROOT / "web/src/engine/gearTable.ts"


def splitmix64(seed: int):
    state = seed
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK64
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        yield z ^ (z >> 31)


def gear_values() -> list[int]:
    gen = splitmix64(SEED)
    return [next(gen) >> 32 for _ in range(256)]


def rows(vals: list[int], indent: str) -> str:
    out = []
    for i in range(0, 256, 6):
        out.append(indent + ", ".join(f"0x{v:08x}" for v in vals[i:i + 6]) + ",")
    return "\n".join(out)


def c_source(vals: list[int]) -> str:
    return f"""/*
 * gear_table.h — GENERATED by scripts/gen_gear.py. Do not edit by hand.
 * SplitMix64(seed 0x{SEED:X}), upper 32 bits of each output (SPEC §6.2).
 * The TypeScript copy in web/src/engine/gearTable.ts must be identical.
 */
#ifndef NX_GEAR_TABLE_H
#define NX_GEAR_TABLE_H

#include <stdint.h>

#define NX_GEAR_SEED 0x{SEED:X}ULL

static const uint32_t NX_GEAR[256] = {{
{rows(vals, "    ")}
}};

#endif
"""


def ts_source(vals: list[int]) -> str:
    return f"""// gearTable.ts — GENERATED by scripts/gen_gear.py. Do not edit by hand.
// SplitMix64(seed 0x{SEED:X}), upper 32 bits of each output (SPEC §6.2).
// Must be identical to server/src/engine/gear_table.h.

export const GEAR_SEED = 0x{SEED:X}n;

// prettier-ignore
export const GEAR: Uint32Array = new Uint32Array([
{rows(vals, "  ")}
]);
"""


def main() -> int:
    vals = gear_values()
    outputs = {C_OUT: c_source(vals), TS_OUT: ts_source(vals)}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run scripts/gen_gear.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
