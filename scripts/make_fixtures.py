#!/usr/bin/env python3
"""Generate deterministic test fixtures (SPEC §6.4).

1. server/tests/fixtures/data/  (git-ignored, ~33 MB, regenerated on demand)
   The 10 chunker fixture files. The same bytes every run on every OS.
2. server/tests/fixtures/crypto_vectors.txt  (committed)
   Expected SHA-256 / SHA-1 / HMAC / PBKDF2 / CRC-32 values computed with
   Python's hashlib, hmac and zlib: an independent reference for the C code.

    python3 scripts/make_fixtures.py          # create whatever is missing
    python3 scripts/make_fixtures.py --force  # rewrite everything

Inputs for the vectors come from SplitMix64 (the C tests implement the same
generator), so the C side can rebuild every input without reading files.
"""
import hashlib
import hmac
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIX = ROOT / "server/tests/fixtures"
DATA = FIX / "data"
MASK64 = (1 << 64) - 1


# ---- deterministic byte sources -------------------------------------------------

def splitmix_bytes(seed: int, n: int) -> bytes:
    """n bytes: successive SplitMix64 outputs, each written little-endian."""
    out = bytearray()
    state = seed & MASK64
    while len(out) < n:
        state = (state + 0x9E3779B97F4A7C15) & MASK64
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        z ^= z >> 31
        out += z.to_bytes(8, "little")
    return bytes(out[:n])


def counter_bytes(tag: str, n: int) -> bytes:
    """Fast pseudo-random bytes for the big fixture files: SHA-256 of
    "tag:i" for i = 0, 1, 2, ... concatenated."""
    out = bytearray()
    i = 0
    while len(out) < n:
        out += hashlib.sha256(f"{tag}:{i}".encode()).digest()
        i += 1
    return bytes(out[:n])


def csv_text(n: int) -> bytes:
    """About n bytes of lab-dataset-like CSV text, truncated to exactly n."""
    names = ["riya", "arjun", "kavya", "aman", "neha", "rohit", "isha", "vikram", "sana", "dev"]
    courses = ["DBMS", "OS", "CN", "TOC", "AI", "ML", "SE", "COA"]
    rows = ["id,student,course,marks,attendance,remark\n"]
    size = len(rows[0])
    rnd = splitmix_bytes(0xC5F, 8 * 300_000)
    i = 0
    while size < n:
        b = rnd[8 * (i % 300_000): 8 * (i % 300_000) + 8]
        row = (f"{i},{names[b[0] % 10]},{courses[b[1] % 8]},{b[2] % 101},"
               f"{60 + b[3] % 41}%,{'ok' if b[4] % 5 else 'needs review'}\n")
        rows.append(row)
        size += len(row)
        i += 1
    return "".join(rows).encode()[:n]


def fixture_files() -> dict[str, bytes]:
    text = csv_text(10 * 1024 * 1024)
    insert = counter_bytes("insert", 300)
    return {
        "f00_empty.bin": b"",
        "f01_1.bin": counter_bytes("f01", 1),
        "f02_2047.bin": counter_bytes("f02", 2047),
        "f03_2048.bin": counter_bytes("f03", 2048),
        "f04_4096.bin": counter_bytes("f04", 4096),
        "f05_16385.bin": counter_bytes("f05", 16385),
        "f06_1mb.bin": counter_bytes("f06", 1024 * 1024),
        "f07_10mb_random.bin": counter_bytes("f07", 10 * 1024 * 1024),
        "f08_10mb_text.csv": text,
        "f09_10mb_text_insert.csv": text[:5000] + insert + text[5000:],
    }


# ---- crypto vectors -------------------------------------------------------------

def vector_lines() -> list[str]:
    lines = [
        "# GENERATED by scripts/make_fixtures.py from Python hashlib/hmac/zlib.",
        "# Inputs are SplitMix64 bytes (seed given per line); see the script.",
        "# sha256 <seed> <len> <hex> | sha1 <seed> <len> <hex> | crc32 <seed> <len> <hex>",
        "# hmac <kseed> <klen> <mseed> <mlen> <hex>",
        "# pbkdf2 <pseed> <plen> <sseed> <slen> <iters> <dklen> <hex>",
    ]
    lens = list(range(0, 260)) + [511, 512, 513, 1000, 4095, 4096, 4097, 65535, 65536, 1_000_003]
    for n in lens:
        seed = 1000 + n
        lines.append(f"sha256 {seed} {n} {hashlib.sha256(splitmix_bytes(seed, n)).hexdigest()}")
    for n in [0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 1000, 65536]:
        seed = 2000 + n
        lines.append(f"sha1 {seed} {n} {hashlib.sha1(splitmix_bytes(seed, n)).hexdigest()}")
    for n in [0, 1, 9, 100, 4096, 70000]:
        seed = 3000 + n
        lines.append(f"crc32 {seed} {n} {zlib.crc32(splitmix_bytes(seed, n)):08x}")
    for klen in [0, 1, 20, 32, 63, 64, 65, 131, 200]:
        for mlen in [0, 1, 55, 56, 64, 1000]:
            ks, ms = 4000 + klen, 5000 + mlen
            mac = hmac.new(splitmix_bytes(ks, klen), splitmix_bytes(ms, mlen), hashlib.sha256)
            lines.append(f"hmac {ks} {klen} {ms} {mlen} {mac.hexdigest()}")
    for plen, slen, iters, dklen in [(0, 0, 1, 32), (8, 16, 1, 32), (8, 16, 2, 32), (10, 16, 1000, 32),
                                     (64, 16, 3, 32), (65, 16, 3, 32), (100, 40, 7, 64), (12, 16, 5, 33),
                                     (12, 16, 4096, 80)]:
        ps, ss = 6000 + plen, 7000 + slen
        dk = hashlib.pbkdf2_hmac("sha256", splitmix_bytes(ps, plen), splitmix_bytes(ss, slen), iters, dklen)
        lines.append(f"pbkdf2 {ps} {plen} {ss} {slen} {iters} {dklen} {dk.hex()}")
    return lines


def main() -> int:
    force = "--force" in sys.argv
    DATA.mkdir(parents=True, exist_ok=True)
    stamp = DATA / ".complete"
    if force or not stamp.exists():
        for name, data in fixture_files().items():
            (DATA / name).write_bytes(data)
        stamp.write_text("ok\n")
        print(f"wrote 10 fixture files to {DATA.relative_to(ROOT)}")
    vec = FIX / "crypto_vectors.txt"
    if force or not vec.exists():
        vec.write_text("\n".join(vector_lines()) + "\n")
        print(f"wrote {vec.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
